    private void btnBorrarTareaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarTareaActionPerformed
        // TODO add your handling code here:
        int fila = tablaDatos.getSelectedRow();
    
    if (fila != -1) {
        // 1. Sacamos el nombre de la asignatura de la fila seleccionada
        String asignaturaABorrar = tablaDatos.getValueAt(fila, 1).toString();
        
        // 2. Lógica de borrado directamente aquí dentro
        java.util.List<String> lineasParaGuardar = new java.util.ArrayList<>();
        
        try {
            // Leemos el archivo
            BufferedReader br = new BufferedReader(new FileReader("datos.txt"));
            String linea;
            while ((linea = br.readLine()) != null) {
                String[] datos = linea.split(",");
                // Comparamos: si no es la asignatura seleccionada, la guardamos
                if (datos.length > 1 && !datos[1].equals(asignaturaABorrar)) {
                    lineasParaGuardar.add(linea);
                }
            }
            br.close();

            // Escribimos el archivo de nuevo
            PrintWriter pw = new PrintWriter(new FileWriter("datos.txt"));
            for (String l : lineasParaGuardar) {
                pw.println(l);
            }
            pw.close();

            // 3. Actualizamos la tabla para que desaparezca visualmente
            cargarDatosTareas();
            javax.swing.JOptionPane.showMessageDialog(this, "Tarea eliminada correctamente.");

        } catch (IOException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al acceder al archivo: " + e.getMessage());
        }
        
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecciona una fila primero.");
    }

    }//GEN-LAST:event_btnBorrarTareaActionPerformed

