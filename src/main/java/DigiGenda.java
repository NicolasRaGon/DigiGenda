public void cargarDatosTareas() {
DefaultTableModel modelo = (DefaultTableModel) tablaDatos.getModel();
    modelo.setRowCount(0); // Limpiamos la tabla

    try (BufferedReader br = new BufferedReader(new FileReader("datos.txt"))) {
        String linea;
        // Solo un bucle while para leer línea por línea
        while ((linea = br.readLine()) != null) {
            String[] datos = linea.split(",");
            if (datos.length >= 3) {
                // Creamos el array de 4 espacios (los que tienes ahora en el diseño)
                Object[] filaConAlerta = new Object[4];
                filaConAlerta[0] = datos[0].trim(); // Tipo
                filaConAlerta[1] = datos[1].trim(); // Asignatura
                filaConAlerta[2] = datos[2].trim(); // Fecha

                // Lógica de Alerta automática
                try {
                    LocalDate fechaTarea = LocalDate.parse(datos[2].trim());
                    LocalDate hoy = LocalDate.now();
                    long diasRestantes = ChronoUnit.DAYS.between(hoy, fechaTarea);

                    if (diasRestantes <= 4 && diasRestantes >= 0) {
                        filaConAlerta[3] = "¡URGENTE!";
                    } else if (diasRestantes < 0) {
                        filaConAlerta[3] = "CADUCADO";
                    } else {
                        filaConAlerta[3] = "---";
                    }
                } catch (Exception e) {
                    filaConAlerta[3] = "Error fecha";
                }

                modelo.addRow(filaConAlerta); // Añadimos la fila a la tabla
            }
        }
    } catch (Exception e) {
        System.out.println("Error al leer datos.txt: " + e.getMessage());
    }
    
    // Aplicamos tu código de ordenación que tenías antes
    TableRowSorter sorter = new TableRowSorter(modelo);
    tablaDatos.setRowSorter(sorter);
    java.util.List<RowSorter.SortKey> sortKeys = new java.util.ArrayList<>();
    sortKeys.add(new RowSorter.SortKey(2, SortOrder.ASCENDING));
    sorter.setSortKeys(sortKeys);
    sorter.sort();
}
public void cargarHorarioDesdeArchivo() {
    File archivo = new File("horario.txt");
    if (!archivo.exists()) return; // Si no hay archivo, no hacemos nada

    try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
        String linea;
        while ((linea = br.readLine()) != null) {
            if (linea.trim().isEmpty()) continue; // Saltamos líneas vacías
            
            String[] datos = linea.split(",");
            if (datos.length >= 3) {
                String dia = datos[0].trim();
                String hora = datos[1].trim();
                String asignatura = datos[2].trim();

                int f = obtenerFilaPorHora(hora);
                int c = obtenerColumnaPorDia(dia);

                if (f != -1 && c != -1) {
                    jTable1.setValueAt(asignatura, f, c);
                }
            }
        }
    } catch (Exception e) {
        // Esto hará que el error salga en la consola de abajo, pero la app abrirá
        System.err.println("Error silencioso al cargar: " + e.getMessage());
    }
}

// Funciones auxiliares para situar los datos
private int obtenerColumnaPorDia(String dia) {
    switch (dia.toUpperCase()) {
        case "LUNES": return 1;
        case "MARTES": return 2;
        case "MIERCOLES": return 3;
        case "JUEVES": return 4;
        case "VIERNES": return 5;
        default: return -1;
    }
}

private int obtenerFilaPorHora(String hora) {
    // Aquí comparas con las horas exactas de tu archivo .txt
    if (hora.contains("08:30")) return 0;
    if (hora.contains("09:25")) return 1;
    if (hora.contains("10:20")) return 2;
    if (hora.contains("11:15")) return 3; // RECREO
    if (hora.contains("11:45")) return 4;
    if (hora.contains("12:40")) return 5;
    if (hora.contains("13:35")) return 6;
    return -1;
}
private void rellenarHorasFijas() {
    // Usamos el nombre jTable1 que es el que sale en tu captura image_3584ba
    String[] horas = {"08:30", "09:25", "10:20", "11:15", "11:45", "12:40", "13:35"};
    
    for (int i = 0; i < horas.length; i++) {
        if (i < jTable1.getRowCount()) {
            jTable1.setValueAt(horas[i], i, 0);
        }
    }
}
