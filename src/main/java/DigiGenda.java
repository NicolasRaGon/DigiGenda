public void guardarEnArchivo(String lineaNueva) {
    try (BufferedWriter bw = new BufferedWriter(new FileWriter("datos.txt", true))) {
        bw.write(lineaNueva);
        bw.newLine(); // Esto hace que la próxima tarea se escriba en una línea nueva
        bw.close();
        
        // Refrescamos la tabla automáticamente para ver la nueva tarea
        cargarDatosTareas();
        
        javax.swing.JOptionPane.showMessageDialog(this, "¡Tarea guardada con éxito!");
    } catch (IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
    }
    
}
